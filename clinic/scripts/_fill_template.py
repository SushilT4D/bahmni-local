#!/usr/bin/env python3
"""Fill a connector template for clinic/connectors/: used by generate-connectors.sh.

usage: _fill_template.py TEMPLATE OUT
       _fill_template.py --mark FILE TEMPLATE   add the "generated" note to FILE

Every ${NAME} whose NAME is set in the environment is replaced, except
passwords (names ending in _PASSWORD): those stay placeholders, and
register-connectors.sh fills them in when it uploads the config, so no
generated file holds a password. Kafka Connect's own placeholders (${topic},
${source.table}) are left for Connect. Any other ${NAME} left unset stops the
script: a connector registered with a literal ${MYSQL_SERVER_NAME} in its topic
prefix reports RUNNING and syncs nothing.

The output carries a "//" key saying it is generated; register-connectors.sh
sends only the "config" object, so Kafka Connect never sees it.
"""
import json, os, re, sys

NOTE = ("Generated by clinic/scripts/generate-connectors.sh from {src}. "
        "Do not edit: change the template or sync/tables/*.conf and run generate-connectors.sh again.")


def fill(value):
    if not isinstance(value, str):
        return value
    def sub(m):
        name = m.group(1)
        if name.endswith('_PASSWORD') or name not in os.environ:
            return m.group(0)
        return os.environ[name]
    return re.sub(r'\$\{([A-Za-z_][A-Za-z0-9_]*)\}', sub, value)


def main(src, out):
    doc = json.load(open(src))
    cfg = {k: fill(v) for k, v in doc['config'].items() if not k.startswith('//')}
    left = sorted({m for v in cfg.values() if isinstance(v, str)
                   for m in re.findall(r'\$\{([A-Za-z_][A-Za-z0-9_]*)\}', v)
                   if not m.endswith('_PASSWORD') and m != 'topic'})
    if left:
        sys.exit(f"{os.path.basename(src)}: not set: {', '.join(left)}")
    write(out, {'//': note(src), 'name': fill(doc['name']), 'config': cfg})


def note(src):
    rel = os.path.relpath(os.path.abspath(src), os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
    return NOTE.format(src=f'clinic/{rel}')


def write(out, doc):
    tmp = out + '.tmp'
    with open(tmp, 'w') as fh:
        json.dump(doc, fh, indent=2)
        fh.write('\n')
    os.replace(tmp, out)


def mark(path, src):
    doc = json.load(open(path))
    write(path, {'//': note(src), **{k: v for k, v in doc.items() if k != '//'}})


if __name__ == '__main__':
    if len(sys.argv) == 4 and sys.argv[1] == '--mark':
        mark(sys.argv[2], sys.argv[3])
    elif len(sys.argv) == 3:
        main(sys.argv[1], sys.argv[2])
    else:
        sys.exit(__doc__)
